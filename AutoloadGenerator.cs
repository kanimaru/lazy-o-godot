using System.Collections.Generic;
using System.Collections.Immutable;
using System.Linq;
using System.Text;
using System.Text.RegularExpressions;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.Text;

namespace GenUtilities;

/// <summary>
/// Typed access to the autoloads of <c>project.godot</c>: for <c>UserService="*res://src/Users/UserService.tscn"</c>,
/// <c>Autoloads.UserService</c> (the node, typed as the C# class its scene's root runs), <c>Autoloads.UserServiceOrNull</c>
/// (<c>null</c> while it is not loaded, as in the editor) and <c>Autoloads.PathUserService</c> (<c>/root/UserService</c>).
/// </summary>
/// <remarks>
/// An autoload is typed by its script: a <c>.cs</c> file's class, the root script's class of a <c>.tscn</c> the project
/// lists as an additional file (else the root's Godot class), and <c>Godot.Node</c> for GDScript.
/// </remarks>
[Generator]
public class AutoloadGenerator : IIncrementalGenerator {
    private const string Namespace = "GenUtilities";
    private const string ClassName = "Autoloads";
    private static readonly Regex Identifier = new("^[A-Za-z_][A-Za-z0-9_]*$");

    public void Initialize(IncrementalGeneratorInitializationContext context) {
        IncrementalValueProvider<ImmutableArray<string>> projectFile = context.AdditionalTextsProvider
            .Where(file => file.Path.EndsWith("project.godot"))
            .Select((file, token) => file.GetText(token)?.ToString() ?? "")
            .Collect();
        IncrementalValueProvider<ImmutableArray<AdditionalText>> scenes = context.AdditionalTextsProvider
            .Where(file => file.Path.EndsWith(".tscn"))
            .Collect();

        context.RegisterSourceOutput(projectFile.Combine(scenes).Combine(context.CompilationProvider),
            (ctx, t) => GenerateCode(ctx, t.Left.Left, t.Left.Right, t.Right));
    }

    private static void GenerateCode(SourceProductionContext context, ImmutableArray<string> projectFiles,
        ImmutableArray<AdditionalText> scenes, Compilation compilation) {
        var members = new StringBuilder();
        foreach ((string name, string path) in projectFiles.SelectMany(Autoloads)) {
            if (!Identifier.IsMatch(name)) {
                continue;
            }

            string type = TypeOf(path, scenes, compilation, context);
            members.AppendLine(
                $$"""
				  	/// <summary>The path of the <c>{{name}}</c> autoload ({{path}}).</summary>
				  	public const string Path{{name}} = "/root/{{name}}";

				  	/// <summary>The <c>{{name}}</c> autoload ({{path}}); fails when it is not loaded.</summary>
				  	public static {{type}} {{name}} => ((global::Godot.SceneTree)global::Godot.Engine.GetMainLoop()).Root.GetNode<{{type}}>(Path{{name}});

				  	/// <summary>The <c>{{name}}</c> autoload ({{path}}), or <c>null</c> while it is not loaded (in the editor, say).</summary>
				  	public static {{type}}? {{name}}OrNull => global::Godot.Engine.GetMainLoop() is global::Godot.SceneTree tree ? tree.Root.GetNodeOrNull<{{type}}>(Path{{name}}) : null;

				  """);
        }

        string code =
            $$"""
			  // <auto-generated/>
			  #nullable enable

			  namespace {{Namespace}};

			  /// <summary>The autoloads of <c>project.godot</c>.</summary>
			  static partial class {{ClassName}}
			  {
			  {{members}}
			  }

			  """;
        context.AddSource($"{Namespace}.{ClassName}.g.cs", SourceText.From(code, Encoding.UTF8));
    }

    /// <summary>The <c>[autoload]</c> entries: their names and the resource each one loads.</summary>
    private static IEnumerable<(string Name, string Path)> Autoloads(string content) {
        bool inSection = false;
        foreach (string raw in content.Split('\n')) {
            string line = raw.TrimEnd('\r');
            if (line.StartsWith("[")) {
                if (inSection) {
                    yield break;
                }

                inSection = line == "[autoload]";
                continue;
            }

            if (!inSection) {
                continue;
            }

            string[] keyValue = line.Split(['='], 2);
            if (keyValue.Length != 2) {
                continue;
            }

            // "*res://..." : the star marks the autoload as a global singleton.
            yield return (keyValue[0].Trim(), keyValue[1].Trim().Trim('"').TrimStart('*'));
        }
    }

    private static string TypeOf(string path, ImmutableArray<AdditionalText> scenes, Compilation compilation, SourceProductionContext context) {
        string resource = path.StartsWith("res://") ? path.Substring("res://".Length) : path;
        if (resource.EndsWith(".cs")) {
            return SceneRoot.NodeClass(compilation, System.IO.Path.GetFileNameWithoutExtension(resource), context.CancellationToken)
                   ?? "global::Godot.Node";
        }

        string? content = null;
        if (resource.EndsWith(".tscn")) {
            AdditionalText? scene = scenes.FirstOrDefault(file => file.Path.Replace('\\', '/').EndsWith("/" + resource));
            content = scene?.GetText(context.CancellationToken)?.ToString();
        } else if (path.StartsWith("uid://")) {
            // The editor writes autoloads by uid; a scene names its own in its header.
            string header = $"uid=\"{path}\"";
            content = scenes
                .Select(file => file.GetText(context.CancellationToken)?.ToString())
                .FirstOrDefault(text => text is not null && text.StartsWith("[gd_scene") && text.Substring(0, text.IndexOf('\n') is var end and > 0 ? end : text.Length).Contains(header));
        }

        return string.IsNullOrEmpty(content)
            ? "global::Godot.Node"
            : SceneRoot.NodeType(compilation, content!, context.CancellationToken);
    }
}
