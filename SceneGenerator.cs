using System.Collections.Generic;
using System.IO;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.Diagnostics;
using Microsoft.CodeAnalysis.Text;

namespace GenUtilities;

[Generator]
public class SceneGenerator : IIncrementalGenerator {
    private const string Namespace = "GenUtilities";


    public void Initialize(IncrementalGeneratorInitializationContext context) {
        IncrementalValuesProvider<AdditionalText> scenes = context.AdditionalTextsProvider
            .Where(text => text.Path.EndsWith(".tscn"));

        context.RegisterSourceOutput(context.CompilationProvider.Combine(scenes.Collect()).Combine(context.AnalyzerConfigOptionsProvider),
            (ctx, t) => GenerateCode(ctx, t.Left.Left, t.Left.Right, t.Right));
    }

    private void GenerateCode(
        SourceProductionContext context,
        Compilation compilation,
        IEnumerable<AdditionalText> scenes,
        AnalyzerConfigOptionsProvider optionsProvider) {
        optionsProvider.GlobalOptions.TryGetValue("build_property.projectdir", out string? projectDirectory);

        var allMethods = new StringBuilder();
        var allPaths = new StringBuilder();
        foreach (AdditionalText scene in scenes) {
            string? directory = Path.GetDirectoryName(scene.Path);
            string name = Path.GetFileNameWithoutExtension(scene.Path);
            string relativePath = scene.Path.Replace(projectDirectory ?? "", "").Replace("\\", "/");
            string member = name.SnakeToCamelCase();
            allPaths.AppendLine($"	public const string Path{member} = \"res://{relativePath}\";");
            // The loaded scene stays referenced, as a GDScript preload keeps it. A wrapper left to the garbage
            // collector races Godot's resource cache: another scene instancing this one after the collection and
            // before the finalizer leaves the C# binding without its GC handle, and every later reference logs
            // "Handle is not initialized" from SwapGCHandleForType.
            allMethods.AppendLine(
                $$"""
				  	private static PackedScene? _packed{{member}};

				  	public static T New{{member}}<T>() where T : Node {
				  		if (_packed{{member}} is null || !GodotObject.IsInstanceValid(_packed{{member}})) {
				  			_packed{{member}} = GD.Load<PackedScene>(Path{{member}});
				  		}

				  		return _packed{{member}}.Instantiate<T>();
				  	}
				  """);

            // A scene whose root runs a C# node class also gets an instantiation typed as that class.
            if (RootType(compilation, scene, context.CancellationToken) is { } rootType) {
                allMethods.AppendLine(
                    $$"""
					  	/// <summary>A new instance of <c>{{relativePath}}</c>.</summary>
					  	public static {{rootType}} New{{member}}() => New{{member}}<{{rootType}}>();
					  """);
            }
        }

        string code =
            $$"""
			  // <auto-generated/>
			  #nullable enable

			  using System;
			  using Godot;

			  namespace {{Namespace}};

			  class Scenes
			  {
			  {{allPaths}}
			  
			  {{allMethods}}
			  }
			  """;
        context.AddSource("GenUtilities.Scenes.g.cs", SourceText.From(code, Encoding.UTF8));
    }

    /// <summary>The fully qualified C# class the scene's root runs, or <c>null</c>; see <see cref="SceneRoot.ScriptClass"/>.</summary>
    private static string? RootType(Compilation compilation, AdditionalText scene, System.Threading.CancellationToken cancellationToken) {
        string? content = scene.GetText(cancellationToken)?.ToString();
        return string.IsNullOrEmpty(content) ? null : SceneRoot.ScriptClass(compilation, content!, cancellationToken);
    }
}
